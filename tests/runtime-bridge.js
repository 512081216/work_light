const assert = require('node:assert/strict');
const { RuntimeObserver, jsonLines } = require('../tools/codex-runtime-bridge');
const o = new RuntimeObserver();
const state = id => o.sessions.get(id).state;
o.server({ method: 'thread/status/changed', params: { threadId: 'market', status: { type: 'active', activeFlags: [] } } });
assert.equal(state('market'), 'executing');
o.server({ id: 7, method: 'mcpServer/elicitation/request', params: { threadId: 'market', message: 'private args' } });
assert.equal(state('market'), 'permission');
o.server({ id: 8, method: 'item/permissions/requestApproval', params: { threadId: 'market' } });
o.client({ id: 7, result: { action: 'accept' } });
assert.equal(state('market'), 'permission');
o.server({ method: 'serverRequest/resolved', params: { threadId: 'market', requestId: 8 } });
assert.equal(state('market'), 'executing');
o.server({ method: 'thread/status/changed', params: { threadId: 'market', status: { type: 'active', activeFlags: ['waitingOnApproval'] } } });
assert.equal(state('market'), 'permission');
o.server({ method: 'turn/completed', params: { threadId: 'market' } });
assert.equal(state('market'), 'idle');
o.server({ method: 'turn/started', params: { threadId: 'market' } });
assert.equal(state('market'), 'executing');
o.server({ id: '9', method: 'item/tool/requestUserInput', params: { threadId: 'other' } });
assert.equal(state('other'), 'permission');
assert.equal(state('market'), 'executing');
assert.ok(!JSON.stringify(o.snapshot()).includes('private args'));
const revision = o.sessions.get('market').revision;
o.server({ method: 'turn/started', params: { threadId: 'market' } });
assert.equal(o.sessions.get('market').revision, revision);
const parsed = []; const read = jsonLines(m => parsed.push(m));
const bytes = Buffer.from(JSON.stringify({ text: '审批' }) + '\ninvalid\n');
for (const byte of bytes) read(Buffer.from([byte]));
assert.deepEqual(parsed, [{ text: '审批' }]);
console.log('PASS: MCP approvals, parallel approvals, responses, runtime flags, completion, isolation, sanitized snapshots, UTF8 framing');
o.server({ id: 'stale-request', method: 'item/permissions/requestApproval', params: { threadId: 'market' } });
assert.equal(state('market'), 'permission');
o.server({ method: 'thread/status/changed', params: { threadId: 'market', status: { type: 'active', activeFlags: [] } } });
assert.equal(state('market'), 'executing');
assert.equal(o.waiting('market'), false);
o.client({ id: 100, method: 'thread/read', params: { threadId: 'market' } });
o.server({ method: 'thread/status/changed', params: { threadId: 'market', status: { type: 'active', activeFlags: [] } } });
o.server({ id: 100, result: { thread: { id: 'market', status: { type: 'active', activeFlags: ['waitingOnApproval'] } } } });
assert.equal(state('market'), 'executing'); // Late pre-resolution read cannot re-open yellow.
o.client({ id: 101, method: 'thread/read', params: { threadId: 'market' } });
o.server({ id: 'new-request', method: 'mcpServer/elicitation/request', params: { threadId: 'market' } });
o.server({ id: 101, result: { thread: { id: 'market', status: { type: 'active', activeFlags: [] } } } });
assert.equal(state('market'), 'permission'); // Old normal read cannot clear a new real approval.
o.client({ id: 102, method: 'thread/read', params: { threadId: 'market' } });
o.server({ method: 'turn/completed', params: { threadId: 'market' } });
o.server({ id: 102, result: { thread: { id: 'market', status: { type: 'active', activeFlags: ['waitingOnApproval'] } } } });
assert.equal(state('market'), 'idle');
assert.equal(state('other'), 'permission'); // Clearing one chat doesn't clear another's wait.
console.log('PASS: authoritative normal state clears stale requests, late read fencing in both directions, terminal fence, other chat isolation');
